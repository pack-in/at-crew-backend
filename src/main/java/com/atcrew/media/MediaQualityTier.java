package com.atcrew.media;

/**
 * 변환 화질 등급 — 요금제-R03("웹 감상에 적합한 화질")·R04("선명한 원본 화질")의 플랜 차등을 담는다.
 *
 * <p>{@link MediaVariantProfile}(성인 블러 파생물 생성 여부)과는 직교하는 축이라 별도 값으로 둔다.
 *
 * <p>화질은 <b>업로드 시점의 플랜</b>으로 확정되며 변환은 1회뿐이다 — 프로 → 스타터 다운그레이드로
 * 이미 올라간 이미지의 화질이 내려가지 않고, 반대로 스타터 시절 업로드분이 프로 전환으로 선명해지지도 않는다.
 */
public enum MediaQualityTier {
    /** 스타터 — 가로 폭 상한을 걸어 축소 저장한다. 웹툰 원고처럼 세로로 긴 이미지를 뭉개지 않도록 긴 변이 아닌 가로 폭 기준이다. */
    WEB,
    /**
     * 프로 — 해상도 상한 없이 q95로 인코딩한다.
     *
     * <p>변환 결과가 raw 원본을 대체한다(Worker가 변환 성공 후 원본을 삭제한다). 그래서 여기서 축소하면
     * 그 해상도를 되돌릴 방법이 없다. q100이 아닌 이유는 Cloudflare가 100에서만 무손실로 넘어가 크기가
     * 급증하기 때문이다(실측 q99 17.6% 대 q100 64.6%) — 자세한 수치는 Worker의 QUALITY_TIERS 주석에 있다.
     */
    ORIGINAL
}
