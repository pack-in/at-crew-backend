package com.atcrew.member;

/** 작화 스타일 — 복수 선택 + 직접입력 (기획서 마이페이지_작가-R23 "작화 스타일(14+직접입력)"). */
public enum DrawingStyle {
    FEMALE_ORIENTED,  // 여성향
    MALE_ORIENTED,    // 남성향
    REALISTIC,        // 실사
    SEMI_REALISTIC,   // 반실사
    THIN_LINE,        // 얇은선
    THICK_LINE,       // 굵은선
    ROUGH_LINE,       // 거친선
    CLEAN_LINE,       // 깔끔한선
    SHOJO,            // 순정만화
    SHONEN,           // 소년만화
    MINIMAL,          // 미니멀
    DARK_TONE,        // 어두운톤
    BRIGHT_TONE,      // 밝은톤
    INK_HEAVY         // 먹칠 위주의 채색
}
